namespace Aspose.Slides.Foss;

/// <summary>
/// Represents NullableBool enumeration.
/// </summary>
public enum NullableBool
{
    /// <summary>
    /// Sentinel/default value.
    /// </summary>
    NotDefined = 0,

    /// <summary>
    /// False value.
    /// </summary>
    False,

    /// <summary>
    /// True value.
    /// </summary>
    True,
}
