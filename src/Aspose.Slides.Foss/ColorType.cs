namespace Aspose.Slides.Foss;

/// <summary>
/// Represents ColorType enumeration.
/// </summary>
public enum ColorType
{
    /// <summary>
    /// Sentinel/default value.
    /// </summary>
    NotDefined = 0,

    /// <summary>
    /// RGB value.
    /// </summary>
    RGB,

    /// <summary>
    /// RGBPercentage value.
    /// </summary>
    RGBPercentage,

    /// <summary>
    /// HSL value.
    /// </summary>
    HSL,

    /// <summary>
    /// Scheme value.
    /// </summary>
    Scheme,

    /// <summary>
    /// System value.
    /// </summary>
    System,

    /// <summary>
    /// Preset value.
    /// </summary>
    Preset,
}
