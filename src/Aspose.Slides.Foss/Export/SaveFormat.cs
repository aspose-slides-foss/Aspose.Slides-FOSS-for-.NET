namespace Aspose.Slides.Foss.Export;

/// <summary>
/// Defines constants representing all supported file formats for saving a presentation.
/// </summary>
public enum SaveFormat
{
    /// <summary>PPT (legacy binary) format.</summary>
    Ppt,

    /// <summary>PDF format.</summary>
    Pdf,

    /// <summary>XPS format.</summary>
    Xps,

    /// <summary>PPTX (Open XML) format.</summary>
    Pptx,

    /// <summary>PPSX slideshow format.</summary>
    Ppsx,

    /// <summary>Multi-page TIFF image.</summary>
    Tiff,

    /// <summary>ODP (OpenDocument Presentation) format.</summary>
    Odp,

    /// <summary>PPTM (macro-enabled presentation) format.</summary>
    Pptm,

    /// <summary>PPSM (macro-enabled slideshow) format.</summary>
    Ppsm,

    /// <summary>POTX (template) format.</summary>
    Potx,

    /// <summary>POTM (macro-enabled template) format.</summary>
    Potm,

    /// <summary>HTML format.</summary>
    Html,

    /// <summary>SWF format.</summary>
    Swf,

    /// <summary>OTP (presentation template) format.</summary>
    Otp,

    /// <summary>PPS format.</summary>
    Pps,

    /// <summary>POT format.</summary>
    Pot,

    /// <summary>FODP (Flat ODP) format.</summary>
    Fodp,

    /// <summary>GIF format.</summary>
    Gif,

    /// <summary>HTML5 (new templating system) format.</summary>
    Html5,

    /// <summary>Markdown format.</summary>
    Md,

    /// <summary>PowerPoint XML Presentation format.</summary>
    Xml
}
