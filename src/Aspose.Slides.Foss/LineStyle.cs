namespace Aspose.Slides.Foss;

/// <summary>
/// Represents LineStyle enumeration.
/// </summary>
public enum LineStyle
{
    /// <summary>
    /// Sentinel/default value.
    /// </summary>
    NotDefined = 0,

    /// <summary>
    /// Single value.
    /// </summary>
    Single,

    /// <summary>
    /// ThinThin value.
    /// </summary>
    ThinThin,

    /// <summary>
    /// ThickThin value.
    /// </summary>
    ThickThin,

    /// <summary>
    /// ThinThick value.
    /// </summary>
    ThinThick,

    /// <summary>
    /// ThickBetweenThin value.
    /// </summary>
    ThickBetweenThin,
}
